# 关键词按长度降序预编译 —— 注释里说的"长词优先"在这里真正生效:
# 同一段文本里,更具体的长词应该赢过短词(例如"美团外卖"优先于"美团")
_KEYWORDS_BY_LENGTH: list[tuple[str, str]] = sorted(
    ((kw, cat) for cat, keywords in CATEGORY_RULES for kw in keywords),
    key=lambda item: len(item[0]),
    reverse=True,
)


def classify(raw_category: str, merchant: str, description: str = "") -> str:
    """根据平台类目 + 商户名 + 描述归类"""
    text = f"{merchant} {description}".lower()

    # 优先级 1: 平台类目
    if raw_category:
        for kw, cat in PLATFORM_CATEGORY_MAP.items():
            if kw in raw_category:
                return cat

    # 优先级 2: 关键词匹配(长词优先)
    for kw, category in _KEYWORDS_BY_LENGTH:
        if kw.lower() in text:
            return category

    return "其他"


def classify_dataframe(df) -> None:
    """对 DataFrame 应用分类,直接修改 df['category'] 列"""
    if df.empty:
        df["category"] = []
        return
    df["category"] = df.apply(
        lambda r: classify(
            str(r.get("raw_category", "")),
            str(r.get("merchant", "")),
            str(r.get("description", "")),
        ),
        axis=1,
    )